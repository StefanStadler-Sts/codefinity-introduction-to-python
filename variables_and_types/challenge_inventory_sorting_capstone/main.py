# Lists of items and categories for slicing
items = "Bubblegum, Chocolate, Pasta"
categories = "Candy Aisle, Pasta Aisle"
candy1 = items[0:9]
candy2 = items[11:20]
dry_goods = items[22:]
print(candy1)
print(candy2)
print(dry_goods)
category1 = categories[0:11]
category2 = categories[13:]
print(category1)
print(category2)
